  <!-- Custom Language Switch Logic -->
  <script>
    const languageSelect = document.getElementById("customLanguage");


    languageSelect.addEventListener("change", function() {
      const lang = this.value;
      if (!lang) return;

      const combo = document.querySelector(".goog-te-combo");
      if (combo) {
        combo.value = lang;
        combo.dispatchEvent(new Event("change"));
      }
      resizeSelectBox(languageSelect);
    });

    // Hide banner that appears on language change
    const observer = new MutationObserver(() => {
      const banner = document.querySelector('iframe.goog-te-banner-frame');
      if (banner) banner.style.display = 'none';
      document.body.style.top = '0px';
    });

    observer.observe(document.body, {
      childList: true,
      subtree: true
    });

    // Sync custom selector with cookie language on page load
    window.addEventListener("load", () => {
      const cookieMatch = document.cookie.match(/googtrans=\/[a-z]{2}\/([a-z]{2})/);
      const currentLang = cookieMatch ? cookieMatch[1] : "";

      if (currentLang) {
        languageSelect.value = currentLang;
      }


    });
  </script>



